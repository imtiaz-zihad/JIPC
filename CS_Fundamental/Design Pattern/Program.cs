/*
What is Design Pattern?
Design Pattern is a reusable solution to a commonly occurring problem in software design. It is a general repeatable solution to a commonly occurring problem in software design. A design pattern isn't a finished design that can be transformed directly into code. It is a description or template for how to solve a problem that can be used in many different situations.  
Design patterns can speed up the development process by providing tested, proven development paradigms. Effective software design requires considering issues that may not become visible until later in the implementation. Reusing design patterns helps to prevent subtle issues that can cause major problems and improves code readability for coders and architects who are familiar with the patterns.

Types are 3 types of Design Patterns:
1. Creational Design Patterns: These patterns deal with object creation mechanisms, trying to create objects in a manner suitable to the situation. The basic form of object creation could lead to design problems or added complexity in the design. Creational design patterns solve this problem by somehow controlling this object creation. Examples include Singleton, Factory Method, Abstract Factory, Builder, and Prototype.

2. Structural Design Patterns: These patterns deal with object composition, creating relationships between objects to form larger structures. They help ensure that if one part of a system changes, the entire system doesn't need to change. Examples include Adapter, Bridge, Composite, Decorator, Facade, Flyweight, and Proxy.

3. Behavioral Design Patterns: These patterns are concerned with algorithms and the assignment of responsibilities between objects. They help in defining how objects interact and communicate with each other. Examples include Chain of Responsibility, Command, Interpreter, Iterator, Mediator, Memento, Observer, State, Strategy, Template Method, and Visitor.        
*/

/*
-----------Creational Design Pattern-----------
1.Singleton Pattern → Ensures only one object of a class exists and provides global access.
2.Factory Method Pattern → Creates objects without specifying the exact class.
3.Abstract Factory Pattern → Creates families of related objects without defining concrete classes.
4.Builder Pattern → Separates object construction from its representation.
5.Prototype Pattern → Creates new objects by cloning existing objects.

-----------Structural Design Pattern-----------
1.Adapter Pattern → Allows incompatible interfaces to work together.
2.Bridge Pattern → Separates abstraction from implementation.
3.Composite Pattern → Organizes objects into tree structures for part-whole hierarchies.
4.Decorator Pattern → Dynamically adds new behavior to objects.
5.Facade Pattern → Provides a simple interface to a complex system.
6.Flyweight Pattern → Shares common data to reduce memory usage.
7.Proxy Pattern → Controls access to another object through a substitute object.


-----------Behavioral Design Pattern-----------
1.Chain of Responsibility Pattern → Passes requests along multiple handlers until handled.
2.Command Pattern → Encapsulates a request as an object.
3.Interpreter Pattern → Interprets sentences based on a defined grammar.
4.Iterator Pattern → Accesses collection elements sequentially without exposing structure.
5.Mediator Pattern → Centralizes communication between objects to reduce coupling.
6.Memento Pattern → Saves and restores an object’s previous state.
7.Observer Pattern → Notifies dependent objects automatically when state changes.
8.State Pattern → Changes object behavior when its internal state changes.
9.Strategy Pattern → Encapsulates interchangeable algorithms.
10.Template Method Pattern → Defines an algorithm structure while subclasses implement steps.
11.Visitor Pattern → Adds new operations to object structures without modifying classes.

